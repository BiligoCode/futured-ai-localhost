/** Details of integrity signals and findings come from the API as loose JSON: read them defensively. */
type Detail = Record<string, unknown>;
const num = (v: unknown) => (typeof v === "number" ? v : 0);
const str = (v: unknown) => (typeof v === "string" ? v : "");
const list = (v: unknown): string[] => (Array.isArray(v) ? v.map(String) : []);
const counts = (v: unknown): [string, number][] =>
  v && typeof v === "object" ? Object.entries(v as Record<string, unknown>).map(([k, n]) => [k, num(n)]) : [];
const items = (v: unknown): Record<string, unknown>[] => (Array.isArray(v) ? v.filter((x) => x && typeof x === "object") : []);

